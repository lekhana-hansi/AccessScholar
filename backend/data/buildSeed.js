const fs = require('fs');
const path = require('path');
const { sources } = require('./seedData');
const { scholarships } = require('./scholarshipsData');
const { isPublishableScholarship, disabilityEligibilityValues } = require('../services/scholarshipService');

const dataDir = path.join(__dirname);
const migrationsDir = path.join(__dirname, '..', 'database', 'migrations');

console.log('--- AccessScholar Seed Generator & Validator ---');
console.log(`Total Sources Defined: ${sources.length}`);
console.log(`Total Scholarships Defined: ${scholarships.length}`);

// 1. Verify sources
const sourceMap = new Map();
for (const s of sources) {
  if (sourceMap.has(s.id)) {
    throw new Error(`Duplicate source ID: ${s.id}`);
  }
  sourceMap.set(s.id, s);
}

// 2. Validate scholarships
let publishableCount = 0;
let pendingCount = 0;
const countryCountMap = new Map();

for (const sch of scholarships) {
  if (sch.verificationStatus === 'verified') {
    const isPub = isPublishableScholarship(sch, sources);
    if (!isPub) {
      console.error('Failed scholarship publishability check:', sch.scholarshipId);
      // Detailed debug
      const sourceIds = Array.isArray(sch.sourceIds) && sch.sourceIds.length ? sch.sourceIds : [sch.sourceId];
      console.error('Source IDs:', sourceIds);
      const related = sourceIds.map((id) => sources.find((item) => item.id === id && item.enabled));
      console.error('Related sources found:', related.map(r => r ? r.id : 'NOT FOUND'));
      try {
        const offUrl = new URL(sch.officialSourceUrl);
        const appUrl = new URL(sch.officialApplicationUrl);
        console.error('Off URL host:', offUrl.hostname);
        console.error('App URL host:', appUrl.hostname);
      } catch (e) {
        console.error('URL parse error:', e.message);
      }
      throw new Error(`Scholarship ${sch.scholarshipId} failed isPublishableScholarship validation!`);
    }
    publishableCount++;
    (sch.studyDestinationCountries || []).forEach((c) => {
      countryCountMap.set(c, (countryCountMap.get(c) || 0) + 1);
    });
  } else if (sch.verificationStatus === 'awaiting_verification') {
    pendingCount++;
  }
}

console.log(`Verified Publishable: ${publishableCount}`);
console.log(`Awaiting Verification: ${pendingCount}`);
console.log('Verified Counts by Study Destination:');
for (const [country, count] of countryCountMap.entries()) {
  console.log(`  - ${country}: ${count}`);
}

// 3. Write sources.json and scholarships.json
fs.writeFileSync(path.join(dataDir, 'sources.json'), JSON.stringify(sources, null, 2) + '\n');
fs.writeFileSync(path.join(dataDir, 'scholarships.json'), JSON.stringify({ scholarships }, null, 2) + '\n');
console.log('Wrote sources.json and scholarships.json successfully.');

// 4. Generate PostgreSQL migration: 002_seed_genuine_scholarships.sql
const sqlLines = [];
sqlLines.push('-- Migration 002: Seed Genuine Official Sources and Worldwide Scholarships');
sqlLines.push('-- Auto-generated by buildSeed.js\n');

// Insert sources
sqlLines.push('-- 1. Insert Official Sources');
for (const s of sources) {
  const hostsSql = `ARRAY[${s.applicationHosts.map(h => `'${h.replace(/'/g, "''")}'`).join(', ')}]::text[]`;
  sqlLines.push(`INSERT INTO scholarship_sources (source_id, source_name, country, official_website, source_type, integration_method, approved_application_hosts, is_active, last_verified_at, last_sync_status)
VALUES ('${s.id}', '${s.name.replace(/'/g, "''")}', '${s.country.replace(/'/g, "''")}', '${s.url}', '${s.sourceType}', '${s.integrationMethod}', ${hostsSql}, true, now(), 'manual_import')
ON CONFLICT (source_id) DO UPDATE SET
  source_name = EXCLUDED.source_name,
  country = EXCLUDED.country,
  official_website = EXCLUDED.official_website,
  source_type = EXCLUDED.source_type,
  approved_application_hosts = EXCLUDED.approved_application_hosts,
  is_active = true,
  updated_at = now();`);
}
sqlLines.push('\n');

// Insert scholarships
sqlLines.push('-- 2. Insert Scholarships');
for (const s of scholarships) {
  const toArraySql = (arr) => arr && arr.length ? `ARRAY[${arr.map(item => `'${String(item).replace(/'/g, "''")}'`).join(', ')}]::text[]` : `ARRAY[]::text[]`;
  const escapeStr = (val) => val === null || val === undefined ? 'NULL' : `'${String(val).replace(/'/g, "''")}'`;
  const escapeNum = (val) => val === null || val === undefined ? 'NULL' : Number(val);
  const escapeJson = (val) => val ? `'${JSON.stringify(val).replace(/'/g, "''")}'::jsonb` : `'{}'::jsonb`;
  const escapeDate = (val) => val ? `'${val}'::date` : 'NULL';
  const escapeTs = (val) => val ? `'${val}'::timestamptz` : 'NULL';

  const titleSql = escapeStr(s.scholarshipName);
  const slugSql = escapeStr(s.scholarshipId);
  const providerSql = escapeStr(s.providerName);
  const providerLogoSql = escapeStr(s.providerLogoUrl);
  const descSql = escapeStr(s.description);
  const eligDescSql = escapeStr(s.eligibilityDetails);
  const catSql = escapeStr(s.scholarshipCategory || 'Scholarship');
  const typeSql = escapeStr(s.scholarshipType || 'International Scholarship');
  const fundingSql = escapeStr(s.fundingType);
  const awardSql = escapeNum(s.awardAmount);
  const currSql = escapeStr(s.currency);
  const levelsSql = toArraySql(s.studyLevels);
  const subjectsSql = toArraySql(s.eligibleSubjects);
  const nationalitiesSql = toArraySql(s.applicantNationalities);
  const residenceSql = toArraySql(s.eligibleResidenceCountries);
  const destinationsSql = toArraySql(s.studyDestinationCountries);
  const disElSql = escapeStr(s.disabilityEligibility || 'unknown');
  const disCatSql = toArraySql(s.disabilityCategories);
  const acadReqSql = escapeJson(s.academicRequirements);
  const incReqSql = escapeJson(s.incomeRequirements);
  const ageReqSql = escapeJson(s.ageRequirements);
  const genderSql = escapeStr(s.genderEligibility);
  const openDateSql = escapeDate(s.applicationOpenDate);
  const deadlineSql = escapeDate(s.applicationDeadline);
  const tzSql = escapeStr(s.deadlineTimezone || 'UTC');
  const srcUrlSql = escapeStr(s.officialSourceUrl);
  const appUrlSql = escapeStr(s.officialApplicationUrl);
  const verStatSql = escapeStr(s.verificationStatus);
  const appStatSql = escapeStr(s.applicationStatus || 'unknown');
  const srcChkSql = escapeTs(s.sourceCheckedAt);
  const lastVerSql = escapeTs(s.lastVerifiedAt);
  const featuredSql = s.featured ? 'true' : 'false';
  const needSql = s.financialNeedRequired === true ? 'true' : (s.financialNeedRequired === false ? 'false' : 'NULL');
  const gpaSql = escapeNum(s.academicRequirements?.minimumGpa);
  const minAgeSql = escapeNum(s.ageRequirements?.minimum);
  const maxAgeSql = escapeNum(s.ageRequirements?.maximum);
  const maxIncSql = escapeNum(s.incomeRequirements?.maximum);

  sqlLines.push(`INSERT INTO scholarships (
  source_id, source_record_id, title, slug, provider_name, provider_logo_url,
  description, eligibility_description, category, scholarship_type, funding_type,
  award_amount, currency, study_levels, eligible_subjects, applicant_nationalities,
  eligible_residence_countries, destination_countries, disability_eligibility, disability_categories,
  academic_requirements, income_requirements, age_requirements, gender_requirements,
  application_open_date, application_deadline, deadline_timezone, official_source_url,
  official_application_url, verification_status, application_status, last_source_checked_at,
  last_verified_at, is_active, is_featured, financial_need_required, minimum_gpa,
  minimum_age, maximum_age, maximum_income, updated_at
) VALUES (
  '${s.sourceId}', '${s.sourceRecordId}', ${titleSql}, ${slugSql}, ${providerSql}, ${providerLogoSql},
  ${descSql}, ${eligDescSql}, ${catSql}, ${typeSql}, ${fundingSql},
  ${awardSql}, ${currSql}, ${levelsSql}, ${subjectsSql}, ${nationalitiesSql},
  ${residenceSql}, ${destinationsSql}, ${disElSql}, ${disCatSql},
  ${acadReqSql}, ${incReqSql}, ${ageReqSql}, ${genderSql},
  ${openDateSql}, ${deadlineSql}, ${tzSql}, ${srcUrlSql},
  ${appUrlSql}, ${verStatSql}, ${appStatSql}, ${srcChkSql},
  ${lastVerSql}, true, ${featuredSql}, ${needSql}, ${gpaSql},
  ${minAgeSql}, ${maxAgeSql}, ${maxIncSql}, now()
)
ON CONFLICT (slug) DO UPDATE SET
  title = EXCLUDED.title,
  provider_name = EXCLUDED.provider_name,
  provider_logo_url = EXCLUDED.provider_logo_url,
  description = EXCLUDED.description,
  eligibility_description = EXCLUDED.eligibility_description,
  category = EXCLUDED.category,
  scholarship_type = EXCLUDED.scholarship_type,
  funding_type = EXCLUDED.funding_type,
  award_amount = EXCLUDED.award_amount,
  currency = EXCLUDED.currency,
  study_levels = EXCLUDED.study_levels,
  eligible_subjects = EXCLUDED.eligible_subjects,
  applicant_nationalities = EXCLUDED.applicant_nationalities,
  eligible_residence_countries = EXCLUDED.eligible_residence_countries,
  destination_countries = EXCLUDED.destination_countries,
  disability_eligibility = EXCLUDED.disability_eligibility,
  disability_categories = EXCLUDED.disability_categories,
  academic_requirements = EXCLUDED.academic_requirements,
  income_requirements = EXCLUDED.income_requirements,
  age_requirements = EXCLUDED.age_requirements,
  gender_requirements = EXCLUDED.gender_requirements,
  application_open_date = EXCLUDED.application_open_date,
  application_deadline = EXCLUDED.application_deadline,
  deadline_timezone = EXCLUDED.deadline_timezone,
  official_source_url = EXCLUDED.official_source_url,
  official_application_url = EXCLUDED.official_application_url,
  verification_status = EXCLUDED.verification_status,
  application_status = EXCLUDED.application_status,
  last_source_checked_at = EXCLUDED.last_source_checked_at,
  last_verified_at = EXCLUDED.last_verified_at,
  is_active = true,
  is_featured = EXCLUDED.is_featured,
  financial_need_required = EXCLUDED.financial_need_required,
  minimum_gpa = EXCLUDED.minimum_gpa,
  minimum_age = EXCLUDED.minimum_age,
  maximum_age = EXCLUDED.maximum_age,
  maximum_income = EXCLUDED.maximum_income,
  last_updated_at = now();`);
}

// Ingestion log record
sqlLines.push('\n-- 3. Record Initial Ingestion Log');
sqlLines.push(`INSERT INTO ingestion_logs (
  status, records_discovered, records_imported, records_updated, records_rejected, duplicate_records, error_message, completed_at
) VALUES (
  'manual_import', ${scholarships.length}, ${publishableCount}, 0, 0, 0, NULL, now()
);`);

fs.writeFileSync(path.join(migrationsDir, '002_seed_genuine_scholarships.sql'), sqlLines.join('\n') + '\n');
console.log('Generated backend/database/migrations/002_seed_genuine_scholarships.sql successfully.');
